from datetime import datetime
from enum import Enum
from pydantic import BaseModel
from typing import Any, Dict, List, Optional


class TaskStatus(str, Enum):
    PENDING = "pending"
    SCRIPTING = "scripting"
    IMAGE_GEN = "image_gen"
    VIDEO_GEN = "video_gen"
    COMPOSING = "composing"
    COMPLETED = "completed"
    FAILED = "failed"


class Scene(BaseModel):
    """A single storyboard panel. Mirrors the cinematic metadata that the
    Director LLM produces and accumulates image / motion URLs as the
    pipeline progresses."""
    scene: int
    title: str
    description: str
    shot_type: str = "Wide Shot"
    lighting: str = "Natural"
    image_prompt: Optional[str] = None
    image_url: Optional[str] = None
    video_url: Optional[str] = None
    motion: Optional[str] = None
    duration_sec: float = 4.0
    dialogue: Optional[str] = None
    sfx: Optional[str] = None
    # Voice-over narration (1-2 sentences) generated by the Composer
    # LLM and rendered to audio by NVIDIA Magpie TTS in the worker.
    narration: Optional[str] = None
    # Per-scene audio path inside the worker volume (populated once
    # TTS completes; the compose step reads it).
    audio_path: Optional[str] = None


class VideoTask(BaseModel):
    id: str
    prompt: str
    status: TaskStatus = TaskStatus.PENDING
    script: Optional[str] = None
    storyboard: List[str] = []  # image URLs, kept for backward compat
    scenes: List[Scene] = []    # rich structured storyboard
    video_urls: List[str] = []
    final_video_url: Optional[str] = None
    title: Optional[str] = None
    logline: Optional[str] = None
    duration_sec: float = 0.0
    error: Optional[str] = None
    created_at: Optional[str] = None
    # Style preset ("cinematic" / "news" / "documentary"). Echoed
    # back to the frontend so the UI can label the run correctly even
    # after a refresh.
    style: Optional[str] = None
    # Video generation mode for this task: "auto" / "image2video" /
    # "text2video". Mirrors the server-side `VIDEO_MODE` config but is
    # captured per-task so the UI can show which mode was used.
    video_mode: str = "auto"
    # Cumulative cost estimate (USD) across the whole pipeline
    # (LLM calls + FLUX image gen + Magpie TTS). Updated by the worker.
    estimated_cost_usd: float = 0.0
    # Per-stage cost breakdown for the UI
    cost_breakdown: dict = {}
    # Stage timing telemetry, e.g. {"scripting": 12.5, "image_gen": 42}.
    # Used by the SSE endpoint to estimate remaining time.
    stage_durations_sec: Dict[str, float] = {}
    # ISO timestamp when the current stage started — used as the
    # ruler against which ETA is computed on every emit.
    current_stage_started_at: Optional[str] = None
    # Per-scene provenance map. Indexed by scene number (1-based).
    # Examples:
    #   "video"       — real Agnes / Runway / video-provider clip
    #   "kenburns"    — fallback: single image stretched to a clip
    #   "missing"     — neither video nor fallback succeeded
    # Lets the UI render a "Slide · fallback" badge on storyboard
    # cards and surface a "rate-limited / unprovisioned" toast on
    # partial renders instead of pretending everything is real.
    scene_provenance: Dict[int, str] = {}
    # Coarse pipeline health roll-up:
    #   "ok"              — every scene used a real video
    #   "partial"         — ≥1 scene fell back to kenburns
    #   "fallback_only"   — every scene fell back (still produces an
    #                        mp4 but it's the slideshow-equivalent)
    #   "missing"         — no usable video OR fallback for ≥1 scene
    render_quality: str = "ok"
    # Free-form human-readable warnings surface to the UI:
    #   "Auto-retry recovered scenes [1, 4]; re-stitched mp4."
    #   "Agnes still rate-limiting; punch through or wait."
    # Decoupled from `error`: failure-level details stay in `error`,
    # recovery notes & advisory messages live here.
    warnings: List[str] = []
    # How many times the workflow has run the auto-retry pass. Bounded
    # by the workflow itself; tracked here so the UI can label "this
    # is your second retry" if the user manually triggers more.
    retry_pass_count: int = 0
